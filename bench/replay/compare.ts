// Renders bench/replay/results.md for a rerun (--after) against an earlier
// run of the same manifest (--before).
//
//   node bench/replay/compare.ts [--after <jsonl>] [--before <jsonl>] [--triage <json>] [--out <md>]
//
// A receipt is useful when the project's tests ran on both sides with
// per-test results: it has entries for single tests (both sides produced a
// machine-readable report) and at least one test passed on both sides.
// triage-r6.json maps a manifest id to why a run was not useful:
// { "<id>": { "category": string, "aver_fault": bool, "note": string } }.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

type Counts = { NEW: number; PREEXISTING: number; FLAKY: number; ENV: number; pass: number };
type Result = {
  id: string;
  repo: string;
  pr: number;
  agent: string;
  state: string;
  aver_commit: string;
  date: string;
  status: "receipt" | "error" | "timeout" | "skipped" | "fetch_error";
  reason?: string;
  wall_ms?: number;
  verdict?: string | null;
  counts?: Counts;
  command_level?: boolean;
  per_test_entries?: number;
  tests_passing_both?: number;
  base_moved_to_merge_base?: boolean;
  base_is_ancestor_of_head?: boolean;
  import_secrets?: number;
  import_placeholders?: number;
  error?: string | null;
};
type Triage = Record<string, { category: string; aver_fault: boolean; note: string }>;

const opt = new Map<string, string>();
for (let i = 2; i < process.argv.length; i += 2) opt.set(process.argv[i].replace(/^--/, ""), process.argv[i + 1]);
const here = import.meta.dirname;
const load = (file: string): Map<string, Result> => {
  const byId = new Map<string, Result>();
  for (const line of readFileSync(file, "utf8").split("\n").filter(Boolean)) {
    const r: Result = JSON.parse(line);
    byId.set(r.id, r);
  }
  return byId;
};
const after = load(resolve(opt.get("after") ?? join(here, "results-r6.jsonl")));
const before = load(resolve(opt.get("before") ?? join(here, "results.jsonl")));
const triageFile = resolve(opt.get("triage") ?? join(here, "triage-r6.json"));
const triage: Triage = existsSync(triageFile) ? JSON.parse(readFileSync(triageFile, "utf8")) : {};
const oldTriageFile = join(here, "triage.json");
const oldTriage: Record<string, { category: string }> = existsSync(oldTriageFile) ? JSON.parse(readFileSync(oldTriageFile, "utf8")) : {};
const outFile = resolve(opt.get("out") ?? join(here, "results.md"));
const manifest: { id: string; row: number }[] = JSON.parse(readFileSync(join(here, "manifest.json"), "utf8")).prs;

const order = manifest.map((m) => m.id);
const ran = (m: Map<string, Result>) => order.map((id) => m.get(id)).filter((r): r is Result => r !== undefined && r.status !== "skipped");
const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${n}/${d} (${Math.round((100 * n) / d)}%)`);
const receipts = (rs: Result[]) => rs.filter((r) => r.status === "receipt");
const perTest = (r: Result) => r.status === "receipt" && (r.per_test_entries ?? (r.command_level === false ? 1 : 0)) > 0;
const useful = (r: Result) => perTest(r) && (r.tests_passing_both ?? 0) > 0;
const any = (r: Result, c: keyof Counts) => (r.counts?.[c] ?? 0) > 0;
const verdicts = (rs: Result[]) => {
  const m = new Map<string, number>();
  for (const r of receipts(rs)) m.set(r.verdict ?? "?", (m.get(r.verdict ?? "?") ?? 0) + 1);
  return ["PASS", "FAIL_OWN", "BLOCKED_NOT_OWN", "UNPROVEN"].filter((v) => m.has(v)).map((v) => `${v} ${m.get(v)}`).join(", ");
};
const informativeBefore = (rs: Result[]) => rs.filter((r) => ["clean run", "genuine regression caught"].includes(oldTriage[r.id]?.category ?? "")).length;

const A = ran(after);
// Compare like with like: the first run's results for the pull requests this
// rerun has reached.
const reached = new Set(A.map((r) => r.id));
const B = ran(before).filter((r) => reached.has(r.id));
const commits = [...new Set(A.map((r) => r.aver_commit.slice(0, 12)))];
const dates = A.map((r) => r.date.slice(0, 10)).sort();

const lines: string[] = [];
const w = (s = "") => lines.push(s);
w("# Replay study: real agent pull requests through `aver ci`");
w();
w("Generated by `node bench/replay/compare.ts` from `results-r6.jsonl` (this rerun), `results.jsonl` (the first run) and the hand triage in `triage-r6.json`.");
w();
w("## Setup");
w();
w(`- **Aver commit:** ${commits.map((c) => `\`${c}\``).join(", ")} (round 6, \`aver ci\`, release build). The first run used \`1a0727d8642c\`.`);
w(`- **Date:** ${dates[0] ?? "-"}${dates.length && dates[0] !== dates[dates.length - 1] ? ` to ${dates[dates.length - 1]}` : ""}.`);
w("- **Dataset:** pull requests from AIDev (Hao Li, Haoxiang Zhang, Ahmed E. Hassan; https://huggingface.co/datasets/hao-li/AIDev, CC-BY-4.0), as listed in [manifest.json](manifest.json). Code was fetched read-only from the public repositories.");
w("- **Machine and invocation:** as in the first run: Apple M1 Pro, Docker Desktop with 8 CPUs and 8 GiB, `runc` sandboxes, `aver ci --repo <bare clone> --base <recorded base> --head <PR head> --home <one fresh persistent home> --fail-on never --sandbox auto`, one pull request at a time, 30-minute limit each. Dependency volumes from a nine-PR pilot of this build were reused (they are keyed by content); the Aver home started empty, so no run was a cache hit from an earlier build.");
w("- **What round 6 changed for these runs:** `aver ci` lists possible secrets and imports files over 64 MiB empty instead of refusing the import; it compares with the merge base when the recorded base is not an ancestor of the head; the default check adds the test runner's reporter (node:test, Vitest, Jest, Mocha, tap) and runs `prepare` and, when the package's entry points are build output, `build` first; `node_modules` is writable through links over the read-only layer; dependency install scripts run in a network-less rebuild; and a command-level check red on both sides is `BLOCKED_NOT_OWN`, not `PASS`.");
w("- **Load:** the replay waits before each pull request until the 1-minute load average is below 20 (`--max-load 20`, recorded as `load_at_start`). The first six rows ran before that gate existed, right after the run started on an idle machine; the machine then slept mid-run, and the runs in flight while it was asleep or heavily loaded were discarded and rerun.");
w("- **Useful receipt:** the project's tests ran on both sides with per-test results: the receipt has entries for single tests (both sides wrote a machine-readable report) and at least one test passed on both sides. This is the round-6 goal metric. For the first run, the comparable number is the hand-triaged informative receipts (every first-run receipt was command-level).");
w();
w("## Before and after");
w();
w(`The rerun has reached ${A.length} of the ${ran(before).length} pull requests the first run ran; it was stopped there to free the machine (it waits for a load average below 20 before each pull request, \`--max-load 20\`, and other agents' builds kept the load far higher for hours), and resumes where it stopped. Both columns cover the same ${A.length} pull requests.`);
w();
w("| | First run (round 4) | Round 6 |");
w("|---|---:|---:|");
w(`| Pull requests compared | ${B.length} | ${A.length} |`);
w(`| Receipts | ${pct(receipts(B).length, B.length)} | ${pct(receipts(A).length, A.length)} |`);
w(`| Errors (no receipt) | ${B.filter((r) => r.status === "error").length} | ${A.filter((r) => r.status === "error").length} |`);
w(`| Timeouts | ${B.filter((r) => r.status === "timeout").length} | ${A.filter((r) => r.status === "timeout").length} |`);
w(`| **Useful receipts** (tests ran on both sides, per test) | ${pct(0, B.length)} (informative by hand triage: ${pct(informativeBefore(B), B.length)}) | **${pct(A.filter(useful).length, A.length)}** |`);
w(`| Receipts with per-test entries | ${B.filter(perTest).length} | ${A.filter(perTest).length} |`);
w(`| Command-level receipts | ${receipts(B).filter((r) => !perTest(r)).length} | ${receipts(A).filter((r) => !perTest(r)).length} |`);
w(`| Verdicts | ${verdicts(B)} | ${verdicts(A)} |`);
w(`| Receipts with a \`NEW\` entry | ${receipts(B).filter((r) => any(r, "NEW")).length} | ${receipts(A).filter((r) => any(r, "NEW")).length} |`);
w(`| Receipts with a \`PREEXISTING\` entry | ${receipts(B).filter((r) => any(r, "PREEXISTING")).length} | ${receipts(A).filter((r) => any(r, "PREEXISTING")).length} |`);
w(`| Receipts with a \`FLAKY\` entry | ${receipts(B).filter((r) => any(r, "FLAKY")).length} | ${receipts(A).filter((r) => any(r, "FLAKY")).length} |`);
w(`| Receipts with an \`ENV\` entry | ${receipts(B).filter((r) => any(r, "ENV")).length} | ${receipts(A).filter((r) => any(r, "ENV")).length} |`);
w(`| Compared with the merge base (recorded base not an ancestor) | 0 of ${B.filter((r) => r.base_is_ancestor_of_head === false).length} | ${A.filter((r) => r.base_moved_to_merge_base).length} of ${A.filter((r) => r.base_is_ancestor_of_head === false).length} |`);
w(`| Imports that listed possible secrets instead of failing | 0 | ${A.filter((r) => (r.import_secrets ?? 0) > 0).length} |`);
w(`| Imports with a file over 64 MiB imported empty | 0 | ${A.filter((r) => (r.import_placeholders ?? 0) > 0).length} |`);
const wall = (rs: Result[]) => rs.map((r) => r.wall_ms ?? 0).sort((a, b) => a - b);
const median = (xs: number[]) => (xs.length ? Math.round(xs[Math.floor(xs.length / 2)] / 1000) : 0);
w(`| Median wall time per pull request | ${median(wall(receipts(B)))} s | ${median(wall(receipts(A)))} s |`);
w();
const notUseful = A.filter((r) => !useful(r));
if (notUseful.length) {
  const cats = new Map<string, { n: number; fault: boolean }>();
  for (const r of notUseful) {
    const t = triage[r.id] ?? { category: "untriaged", aver_fault: false };
    const c = cats.get(t.category) ?? { n: 0, fault: t.aver_fault };
    c.n++;
    cats.set(t.category, c);
  }
  w("### Why the remaining runs are not useful");
  w();
  w("| Reason | Pull requests | Aver's fault |");
  w("|---|---:|---|");
  for (const [cat, { n, fault }] of [...cats].sort((a, b) => b[1].n - a[1].n)) w(`| ${cat} | ${n} | ${fault ? "yes" : "no"} |`);
  w();
}
w("## Per pull request");
w();
w("*First run* is the first run's verdict (or error) and its hand triage. *Tests* is entries for single tests, *both* the tests that passed on both sides. Counts are receipt entries by cause. *Base* is `merge` when Aver compared with the merge base because the recorded base is not an ancestor of the head.");
w();
w("| # | Pull request | First run | Round 6 | Tests | Both | NEW | PRE | FLAKY | ENV | Base | Time | Useful |");
w("|---:|---|---|---|---:|---:|---:|---:|---:|---:|---|---:|---|");
for (const r of A) {
  const b = before.get(r.id);
  const m = manifest.find((x) => x.id === r.id);
  const c = r.counts;
  const first = b ? `${b.verdict ?? b.status.toUpperCase()}${oldTriage[r.id] ? ` (${oldTriage[r.id].category})` : ""}` : "-";
  w(
    `| ${m?.row ?? ""} | [${r.repo}#${r.pr}](https://github.com/${r.repo}/pull/${r.pr}) | ${first} | ${r.verdict ?? r.status.toUpperCase()} | ${r.per_test_entries ?? "-"} | ${r.tests_passing_both ?? "-"} | ${c?.NEW ?? "-"} | ${c?.PREEXISTING ?? "-"} | ${c?.FLAKY ?? "-"} | ${c?.ENV ?? "-"} | ${r.base_moved_to_merge_base ? "merge" : ""} | ${r.wall_ms ? `${Math.round(r.wall_ms / 1000)} s` : "-"} | ${useful(r) ? "yes" : "no"} |`,
  );
}
w();
const noted = A.filter((r) => triage[r.id]);
if (noted.length) {
  w("### Triage notes");
  w();
  for (const r of noted) w(`- **${r.repo}#${r.pr}** (${triage[r.id].category}${triage[r.id].aver_fault ? ", Aver" : ""}): ${triage[r.id].note}`);
  w();
}
const skipped = order.map((id) => after.get(id)).filter((r): r is Result => r?.status === "skipped");
w("## Skipped");
w();
for (const r of skipped) w(`- ${r.repo}#${r.pr}: ${r.reason}`);
if (!skipped.length) w("None.");
w();
writeFileSync(outFile, lines.join("\n"));
console.log(`wrote ${outFile}`);
