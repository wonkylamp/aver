// Renders bench/replay/results-first.md (the first run) from results.jsonl, the manifest and the
// hand-written triage.json.
//
//   node bench/replay/summarize.ts [--results <jsonl>] [--triage <json>] [--out <md>]
//
// triage.json maps a manifest id to what a person concluded after reading the
// run's output: { "<id>": { "category": string, "aver_fault": bool, "note": string } }.
// Categories with aver_fault true are what Aver must fix.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

type Result = {
  id: string;
  repo: string;
  pr: number;
  agent: string;
  state: string;
  aver_commit: string;
  date: string;
  status: "receipt" | "error" | "timeout" | "skipped" | "fetch_error";
  reason?: string;
  exit_code?: number | null;
  wall_ms?: number;
  verdict?: string | null;
  base_is_ancestor_of_head?: boolean;
  merge_parent?: string | null;
  recorded_base?: string;
  pr_test_files?: string[];
  pr_test_files_deleted?: string[];
  counts?: { NEW: number; PREEXISTING: number; FLAKY: number; ENV: number; pass: number };
  base_failed?: boolean;
  command_level?: boolean;
  entries?: number;
  failing?: { id: string; base: string; head: string; cause: string }[];
  error?: string | null;
};
// base_red_by overrides aver_fault when saying whose fault a red base was.
type Triage = Record<string, { category: string; aver_fault: boolean; note: string; base_red_by?: "aver" | "project" }>;

const opt = new Map<string, string>();
for (let i = 2; i < process.argv.length; i += 2) opt.set(process.argv[i].replace(/^--/, ""), process.argv[i + 1]);
const here = import.meta.dirname;
const resultsFile = resolve(opt.get("results") ?? join(here, "results.jsonl"));
const triageFile = resolve(opt.get("triage") ?? join(here, "triage.json"));
const outFile = resolve(opt.get("out") ?? join(here, "results-first.md"));

// The last line for an id wins, so a rerun replaces an earlier result.
const byId = new Map<string, Result>();
for (const line of readFileSync(resultsFile, "utf8").split("\n").filter(Boolean)) {
  const r: Result = JSON.parse(line);
  byId.set(r.id, r);
}
const manifest: { id: string; rank: number | null; row: number }[] = JSON.parse(readFileSync(join(here, "manifest.json"), "utf8")).prs;
const order = new Map(manifest.map((m, i) => [m.id, i]));
const results = [...byId.values()].sort((a, b) => (order.get(a.id) ?? 0) - (order.get(b.id) ?? 0));
const triage: Triage = existsSync(triageFile) ? JSON.parse(readFileSync(triageFile, "utf8")) : {};

const skipped = results.filter((r) => r.status === "skipped");
const ran = results.filter((r) => r.status !== "skipped");
const withReceipt = ran.filter((r) => r.status === "receipt");
const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${n}/${d} (${Math.round((100 * n) / d)}%)`);
const anyCause = (r: Result, c: "NEW" | "PREEXISTING" | "FLAKY" | "ENV") => (r.counts?.[c] ?? 0) > 0;
const baseRed = (r: Result) => r.base_failed === true || anyCause(r, "PREEXISTING");
const touchedTests = (r: Result) => (r.pr_test_files ?? []).length > 0;
const averFault = (r: Result) => triage[r.id]?.aver_fault === true;

const commits = [...new Set(ran.map((r) => r.aver_commit))];
const dates = ran.map((r) => r.date.slice(0, 10)).sort();
const verdicts = new Map<string, number>();
for (const r of withReceipt) verdicts.set(r.verdict ?? "?", (verdicts.get(r.verdict ?? "?") ?? 0) + 1);

const lines: string[] = [];
const w = (s = "") => lines.push(s);
w("# Replay study: real agent pull requests through `aver ci`");
w();
w("Generated by `node bench/replay/summarize.ts` from `results.jsonl` and the hand triage in `triage.json`.");
w();
w("## Setup");
w();
w(`- **Aver commit:** ${commits.map((c) => `\`${c.slice(0, 12)}\``).join(", ")} (\`aver ci\`, release build).`);
w(`- **Date:** ${dates[0] ?? "-"}${dates.length && dates[0] !== dates[dates.length - 1] ? ` to ${dates[dates.length - 1]}` : ""}.`);
w("- **Machine:** Apple M1 Pro laptop (8 cores, 16 GiB), Docker Desktop (Linux VM with 8 CPUs and 8 GiB), `linux/arm64` sandboxes under hardened `runc`. gVisor was not installed, so `--sandbox auto` used `runc` for every run.");
w("- **Invocation:** `aver ci --repo <bare clone> --base <recorded base> --head <PR head> --home <one persistent home> --fail-on never --sandbox auto`, one pull request at a time, with a 30-minute wall-clock limit each. Other Docker workloads (another agent's test suites and a local web stack) shared the VM during the runs, which matters for timeout-driven flakiness. No pull request has an `aver.toml`, so every run used Aver's default environment: the pinned `node:22-bookworm-slim` image, `npm ci --ignore-scripts`, and one check `npm test` with no JUnit report.");
w("- **Rules:** round-3 verdict rules. No criteria were declared, so every receipt is regression-only (`aver.receipt/v1`): the verdict is `FAIL_OWN` for any `NEW`, `BLOCKED_NOT_OWN` for any `ENV`, else `PASS`. There is no transplant proof, and the harness (`package.json` scripts, lockfile, test config, the tests themselves) is taken from the head, so a pull request that edits its own tests or test script is judged by what it edited.");
w("- **Base:** GitHub's recorded `baseRefOid` for the pull request (the base-branch tip it was last compared against). Where that commit is not an ancestor of the head, the diff Aver judges also contains the base branch's newer commits, reversed. The table marks those rows.");
w("- **Dataset:** pull requests from AIDev (Hao Li, Haoxiang Zhang, Ahmed E. Hassan; https://huggingface.co/datasets/hao-li/AIDev, CC-BY-4.0), filtered to TypeScript and JavaScript repositories with an npm lockfile and a `test` script, then screened against GitHub. The manifest is [manifest.json](manifest.json). Code was fetched read-only from the public repositories.");
w();
w("## Aggregates");
w();
w(`- Pull requests in the manifest: ${manifest.length}. Ran: ${ran.length}. Skipped before running: ${skipped.length}.`);
w(`- Runs that produced a receipt: ${pct(withReceipt.length, ran.length)}. Errors (exit 2, no receipt): ${ran.filter((r) => r.status === "error").length}. Timeouts: ${ran.filter((r) => r.status === "timeout").length}.`);
w(`- Verdicts: ${[...verdicts].map(([v, n]) => `${v} ${n}`).join(", ") || "none"}.`);
w(`- **Base-red rate** (the base already had a failing check): ${pct(withReceipt.filter(baseRed).length, withReceipt.length)}.`);
if (Object.keys(triage).length) {
  const red = withReceipt.filter(baseRed);
  const redByAver = (r: Result) => (triage[r.id]?.base_red_by ?? (averFault(r) ? "aver" : "project")) === "aver";
  w(`  - Of those, triaged as Aver's fault (the base was red because of the sandbox or default environment): ${red.filter(redByAver).length}; the project's own (network, Node version, VS Code runtime, a real failing test): ${red.filter((r) => !redByAver(r)).length}.`);
  const informative = withReceipt.filter((r) => ["clean run", "genuine regression caught"].includes(triage[r.id]?.category ?? ""));
  w(`- **Informative receipts** (the project's tests ran to completion on both sides, so the verdict reflects the change): ${pct(informative.length, ran.length)} of the pull requests run.`);
}
w(`- \`ENV\` entries: ${withReceipt.reduce((n, r) => n + (r.counts?.ENV ?? 0), 0)}. Every environment failure above surfaced as a check that fails on both sides, so it is counted as \`PREEXISTING\` and the verdict is \`PASS\`, not \`BLOCKED_NOT_OWN\`.`);
w(`- **Agent-broke-something rate** (any \`NEW\`): ${pct(withReceipt.filter((r) => anyCause(r, "NEW")).length, withReceipt.length)}.`);
w(`- **Flaky rate** (any \`FLAKY\`): ${pct(withReceipt.filter((r) => anyCause(r, "FLAKY")).length, withReceipt.length)}.`);
w(`- **Env/unsupported rate** (any \`ENV\`, no receipt, or a triaged Aver-side cause): ${pct(ran.filter((r) => anyCause(r, "ENV") || r.status !== "receipt" || averFault(r)).length, ran.length)}.`);
w(`- Receipts at test granularity (JUnit): ${withReceipt.filter((r) => r.command_level === false).length}; command-level only: ${withReceipt.filter((r) => r.command_level !== false).length}.`);
w(`- Pull requests that touched test files: ${pct(ran.filter(touchedTests).length, ran.length)}; that deleted a test file: ${ran.filter((r) => (r.pr_test_files_deleted ?? []).length > 0).length}.`);
w(`- Recorded base not an ancestor of the head: ${ran.filter((r) => r.base_is_ancestor_of_head === false).length}.`);
w();
const reasons = new Map<string, { n: number; fault: boolean }>();
for (const r of ran) {
  const t = triage[r.id];
  if (!t) continue;
  const cur = reasons.get(t.category) ?? { n: 0, fault: t.aver_fault };
  cur.n++;
  reasons.set(t.category, cur);
}
if (reasons.size) {
  w("### Triage categories");
  w();
  w("| Category | Pull requests | Aver's fault |");
  w("|---|---:|---|");
  for (const [cat, { n, fault }] of [...reasons].sort((a, b) => b[1].n - a[1].n)) w(`| ${cat} | ${n} | ${fault ? "yes" : "no"} |`);
  w();
}
w("## Per pull request");
w();
w("Counts are receipt entries by cause. With no JUnit report every receipt has one command-level entry (`test`), so a count of 1 means the whole `npm test` run. *Tests* is test files the pull request changed (D = deleted). *Base* marks a recorded base that is not an ancestor of the head (`!`). *Time* is the wall time of `aver ci` (imports, installs, checks; cloning excluded). An import rejection takes about a second. Two pilot rows (npq#375 and json-mask#173) were recorded a second time after a harness restart and were answered from the persistent home's run cache, so their time is about a second.");
w();
w("| # | Pull request | Agent | State | Verdict | NEW | PRE | FLAKY | ENV | Tests | Base | Time | Triage |");
w("|---:|---|---|---|---|---:|---:|---:|---:|---|---|---:|---|");
for (const r of ran) {
  const c = r.counts;
  const t = triage[r.id];
  const tests = (r.pr_test_files ?? []).length;
  const del = (r.pr_test_files_deleted ?? []).length;
  const m = manifest.find((x) => x.id === r.id);
  w(
    `| ${m?.row ?? ""} | [${r.repo}#${r.pr}](https://github.com/${r.repo}/pull/${r.pr}) | ${r.agent} | ${r.state} | ${r.verdict ?? r.status.toUpperCase()} | ${c?.NEW ?? "-"} | ${c?.PREEXISTING ?? "-"} | ${c?.FLAKY ?? "-"} | ${c?.ENV ?? "-"} | ${tests ? `${tests}${del ? ` (${del} D)` : ""}` : "no"} | ${r.base_is_ancestor_of_head === false ? "!" : ""} | ${r.wall_ms ? `${Math.round(r.wall_ms / 1000)} s` : "-"} | ${t ? `${t.category}${t.aver_fault ? " (Aver)" : ""}` : ""} |`,
  );
}
w();
if (Object.keys(triage).length) {
  w("### Triage notes");
  w();
  for (const r of ran) {
    const t = triage[r.id];
    if (t) w(`- **${r.repo}#${r.pr}**: ${t.note}`);
  }
  w();
}
w("## Skipped");
w();
for (const r of skipped) w(`- ${r.repo}#${r.pr}: ${r.reason}`);
if (!skipped.length) w("None.");
w();
writeFileSync(outFile, lines.join("\n"));
console.log(`wrote ${outFile}`);
