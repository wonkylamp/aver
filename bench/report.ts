// Renders bench/results/*.json as Markdown on stdout. Run by bench/run.sh.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { cpus, platform, release, totalmem } from "node:os";

type Stats = { n: number; mean_us: number; p50_us: number; p95_us: number; p99_us: number; max_us: number };
type Workspaces = {
  base: { snapshot: string; synthetic: boolean; files: number };
  open_in_process: Stats;
  open_http: Stats;
  storage: { workspaces: number; bytes_per_workspace: number; http_bytes_per_workspace: number };
  edit_one_file: { workspaces: number; time: Stats; new_objects_mean: number };
  snapshot_after_edit: { workspaces: number; time: Stats; new_objects_mean: number; new_objects_max: number };
};
type Import = {
  repo: string;
  commit: string;
  files: number;
  typescript_files: number;
  typescript_lines: number;
  total_bytes: number;
  objects_written: number;
  import_ms: number;
  reimport_ms: number;
  export_ms: number;
  tree_sha: string;
  tree_sha_matches: boolean;
  db_bytes: number;
};
type Pass = {
  pass: number;
  ms: number;
  checks: number;
  sandboxes_started: number;
  cache_hits: number;
  outcomes: { check: string; outcome: string; tests: number }[];
};
type Cache = { fixture: string; executor: string; passes: Pass[]; second_pass_served_from_cache: boolean };
type Timing = { median_ms: number; p95_ms: number; max_ms: number };
type Search = {
  files: number;
  runs: number;
  cpus: number;
  search: { query: string; pattern: string; matches: number; truncated: boolean; files_searched: number; time: Timing }[];
  tree: { query: string; entries: number; time: Timing }[];
};

const load = <T>(name: string): T => JSON.parse(readFileSync(new URL(`results/${name}`, import.meta.url), "utf8")) as T;
const tryRun = (cmd: string, args: string[]) => {
  try {
    return execFileSync(cmd, args, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "unknown";
  }
};

const imp = load<Import>("import.json");
const real = load<Workspaces>("workspaces-date-fns.json");
const synthetic = load<Workspaces>("workspaces.json");
const cache = load<Cache>("cache.json");
const search = load<Search>("search.json");

const mib = (b: number) => `${(b / 1024 / 1024).toFixed(1)} MiB`;
const ms = (v: number) => `${Math.round(v)} ms`;
const us = (v: number) => `${v.toFixed(1)} µs`;
const int = (v: number) => v.toLocaleString("en-US");
const os = platform() === "darwin" ? `macOS ${tryRun("sw_vers", ["-productVersion"])}` : `${platform()} ${release()}`;
const model = platform() === "darwin" ? tryRun("sysctl", ["-n", "hw.model"]) : "";

const row = (cells: (string | number)[]) => `| ${cells.join(" | ")} |`;
const statRow = (label: string, s: Stats) => row([label, int(s.n), us(s.mean_us), us(s.p50_us), us(s.p95_us), us(s.p99_us), us(s.max_us)]);
const workspaceTable = (w: Workspaces) =>
  [
    row(["Operation", "n", "mean", "p50", "p95", "p99", "max"]),
    row(["---", "---:", "---:", "---:", "---:", "---:", "---:"]),
    statRow("Open, in process", w.open_in_process),
    statRow("Open, signed HTTP", w.open_http),
    statRow("Edit one file", w.edit_one_file.time),
    statRow("Snapshot after the edit", w.snapshot_after_edit.time),
  ].join("\n");

const outcomes = (p: Pass) => p.outcomes.map((o) => `${o.check}: ${o.outcome} (${o.tests} tests)`).join(", ");
const [first, second] = cache.passes;
if (!first || !second) throw new Error("cache.json needs two passes");

console.log(`# Benchmark results

Generated by \`make bench\` on ${new Date().toISOString().slice(0, 10)}. Release build. Rerun \`make bench\` to regenerate this file.

**Machine.** ${model ? `${model}, ` : ""}${cpus()[0]?.model ?? "unknown CPU"}, ${cpus().length} cores, ${Math.round(totalmem() / 1024 ** 3)} GiB RAM, ${os}, Docker ${tryRun("docker", ["version", "--format", "{{.Server.Version}}"])}, sandbox profile \`${cache.executor}\`.

## Import: date-fns

[date-fns](https://github.com/date-fns/date-fns) at \`${imp.commit}\`, fetched bare and never checked out.

| Measure | Value |
|---|---:|
| Files | ${int(imp.files)} |
| TypeScript files | ${int(imp.typescript_files)} |
| TypeScript lines | ${int(imp.typescript_lines)} |
| Bytes imported | ${mib(imp.total_bytes)} |
| Objects written | ${int(imp.objects_written)} |
| Import | ${ms(imp.import_ms)} |
| Re-import (no new objects) | ${ms(imp.reimport_ms)} |
| Export round trip to a new bare repository | ${ms(imp.export_ms)} |
| Exported tree SHA equals the original \`${imp.tree_sha.slice(0, 12)}\` | ${imp.tree_sha_matches ? "yes" : "**no**"} |
| Database size after import | ${mib(imp.db_bytes)} |

## Workspaces: 1,000 on the date-fns snapshot

Base \`${real.base.snapshot}\`, ${int(real.base.files)} files. Opens are sequential; each one is a database row, so the snapshot's size does not change the cost.

${workspaceTable(real)}

Storage is the growth of the database and its WAL after a checkpoint, which SQLite allocates in whole pages.

| Storage per workspace | Bytes |
|---|---:|
| In process (no request audit row) | ${real.storage.bytes_per_workspace.toFixed(0)} |
| Over HTTP, including the signed-request audit row | ${real.storage.http_bytes_per_workspace.toFixed(0)} |

Editing one file writes ${real.edit_one_file.new_objects_mean} new object (the blob). Snapshotting that workspace writes ${real.snapshot_after_edit.new_objects_mean} on average (max ${real.snapshot_after_edit.new_objects_max}): the changed trees on the path to the root and the snapshot.

## Workspaces: 1,000 on the synthetic base

A generated base of ${int(synthetic.base.files)} files in 210 directories, for comparison with the real snapshot.

${workspaceTable(synthetic)}

Storage per workspace: ${synthetic.storage.bytes_per_workspace.toFixed(0)} bytes in process, ${synthetic.storage.http_bytes_per_workspace.toFixed(0)} bytes over HTTP with the audit row.

## Cache: a second run of the same checks

Every check of \`${cache.fixture}\`, run twice on one snapshot with real Docker sandboxes.

| Pass | Time | Checks | Outcomes | Sandboxes started | Cache hits |
|---|---:|---:|---|---:|---:|
| 1 | ${ms(first.ms)} | ${first.checks} | ${outcomes(first)} | ${first.sandboxes_started} | ${first.cache_hits} |
| 2 | ${second.ms.toFixed(1)} ms | ${second.checks} | ${outcomes(second)} | ${second.sandboxes_started} | ${second.cache_hits} |

Second pass served entirely from cache: ${cache.second_pass_served_from_cache ? "yes (zero sandboxes, the same run ids)" : "**no**"}. The calc base fails its \`divide\` tests on purpose (it is the task fixture), and failing runs are cached like passing ones. A second \`verify\` of the same base and head likewise starts no sandboxes.

## Search and tree: the date-fns workspace

\`workspace_search\` and \`workspace_tree\` over a workspace on the date-fns snapshot (${int(search.files)} files) with one edited file, in process, ${search.runs} timed runs each after one warm-up, ${search.cpus} cores. Search reads blobs from the store on up to eight threads and returns at most 100 matches.

| Query | Matches | Files read | Median | p95 |
|---|---:|---:|---:|---:|
${search.search.map((q) => row([q.query, q.matches, int(q.files_searched), `${q.time.median_ms} ms`, `${q.time.p95_ms} ms`])).join("\n")}

| Listing | Entries | Median | p95 |
|---|---:|---:|---:|
${search.tree.map((q) => row([q.query, int(q.entries), `${q.time.median_ms} ms`, `${q.time.p95_ms} ms`])).join("\n")}`);
