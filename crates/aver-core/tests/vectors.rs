//! Generates `schemas/vectors/v0.json`, the cross-language test vectors, and
//! fails when the committed file is stale. Regenerate with
//! `AVER_REGEN_VECTORS=1 cargo test -p aver-core --test vectors`.

mod common;

use aver_core::canonical::to_canonical;
use aver_core::*;
use common::*;
use data_encoding::HEXLOWER;
use serde_json::{json, Value};

const VECTORS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../schemas/vectors/v0.json");

const CANONICAL_INPUTS: &[&str] = &[
    r#"{ "b": 1, "a": [3, 1, 2] }"#,
    r#"{"a":1,"B":2,"_":3,"aa":4,"a_":5}"#,
    r#"{"nested":{"z":null,"y":true,"x":false},"empty":{},"list":[]}"#,
    r#"[9007199254740991, -9007199254740991, 0, -1]"#,
    r#""\u00e9 \u2028 / \ud83d\ude00""#,
    r#""quote\" backslash\\ tab\t newline\n return\r backspace\b formfeed\f""#,
    r#""\u0000\u0001\u001f\u007f""#,
];

const CANONICAL_REJECTED: &[(&str, &str)] = &[
    ("1.5", "float"),
    ("1.0", "float, even when integral"),
    ("1e2", "float in exponent form"),
    ("9007199254740992", "integer above 2^53-1"),
    ("-9007199254740992", "integer below -(2^53-1)"),
    (r#"{"é":1}"#, "non-ASCII object key"),
];

fn text(bytes: &[u8]) -> String {
    String::from_utf8(bytes.to_vec()).unwrap()
}

fn build() -> Value {
    let key = key();
    let public_key = key.verifying_key();

    let canonical_json: Vec<Value> = CANONICAL_INPUTS
        .iter()
        .map(|input| {
            let value: Value = serde_json::from_str(input).unwrap();
            json!({ "input": input, "output": text(&to_canonical(&value).unwrap()) })
        })
        .collect();
    let canonical_rejected: Vec<Value> = CANONICAL_REJECTED
        .iter()
        .map(|(input, reason)| {
            let value: Value = serde_json::from_str(input).unwrap();
            assert!(to_canonical(&value).is_err(), "{input} must be rejected");
            json!({ "input": input, "reason": reason })
        })
        .collect();

    let blob_bytes = b"hello\n";
    let tree = sample_tree();
    let env = sample_env();
    let snapshot = sample_snapshot();

    let transition = sample_transition();
    let unsigned = serde_json::to_value(&transition.body).unwrap();
    let base64url = base64url_vectors(
        &transition.signature.sig.to_base64url(),
        &data_encoding::BASE64URL_NOPAD.encode(public_key.as_bytes()),
    );

    json!({
        "description": "Aver v0 cross-language vectors, generated by crates/aver-core/tests/vectors.rs. Ids are prefix + '_' + lowercase unpadded base32(BLAKE3('aver:' + prefix + 0x00 + body)). Byte strings are lowercase hex unless named *_utf8.",
        "canonical_json": canonical_json,
        "canonical_json_rejected": canonical_rejected,
        "key": {
            "seed_hex": HEXLOWER.encode(&SEED),
            "public_key_hex": HEXLOWER.encode(public_key.as_bytes()),
            "agent_id": AgentId::of_public_key(&public_key).to_string(),
        },
        "ids": [
            {
                "prefix": "blob",
                "body_utf8": text(blob_bytes),
                "id": BlobId::of_bytes(blob_bytes).to_string(),
            },
            {
                "prefix": "tree",
                "body_utf8": text(&tree.canonical_bytes()),
                "id": tree.id().to_string(),
            },
            {
                "prefix": "env",
                "body_utf8": text(&env.canonical_bytes()),
                "id": env.id().to_string(),
            },
            {
                "prefix": "env",
                "body_utf8": text(&sample_env_v1().canonical_bytes()),
                "id": sample_env_v1().id().to_string(),
            },
            {
                "prefix": "snap",
                "body_utf8": text(&snapshot.canonical_bytes()),
                "id": snapshot.id().to_string(),
            },
            {
                "prefix": "snap",
                "body_utf8": text(&sample_snapshot_v1().canonical_bytes()),
                "id": sample_snapshot_v1().id().to_string(),
            },
            {
                "prefix": "ctr",
                "body_utf8": text(&sample_contract().canonical_bytes()),
                "id": sample_contract().id().to_string(),
            },
        ],
        "object_signature": {
            "prefix": "tran",
            "unsigned_utf8": text(&to_canonical(&unsigned).unwrap()),
            "message_hex": HEXLOWER.encode(&Transition::signing_message(&transition.body)),
            "signature_base64url": transition.signature.sig.to_base64url(),
            "signed_utf8": text(&transition.canonical_bytes()),
            "id": transition.id().to_string(),
        },
        "base64url": base64url,
        "signed_objects": [
            signed_vector(&sample_task()),
            signed_vector(&sample_task_v1()),
            signed_vector(&sample_task_v2()),
            signed_vector(&sample_receipt()),
            signed_vector(&sample_receipt_v1()),
            signed_vector(&sample_receipt_v2()),
            signed_vector(&sample_receipt_v3()),
        ],
    })
}

const ALPHABET: &str = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";

/// `text` with its last character's lowest bit set, which only changes bits
/// that the canonical encoding leaves zero.
fn low_bit_set(text: &str) -> String {
    let (head, last) = text.split_at(text.len() - 1);
    let index = ALPHABET.find(last).unwrap();
    assert_eq!(index & 1, 0, "canonical text has zero unused bits");
    format!("{head}{}", &ALPHABET[index | 1..=index | 1])
}

/// Canonical unpadded base64url strings and near misses every decoder must
/// refuse: each rejected string differs from a canonical one only
/// in its encoding, so accepting it would give one value several encodings.
fn base64url_vectors(signature: &str, public_key: &str) -> Value {
    let accepted: Vec<Value> = [signature, public_key]
        .iter()
        .map(|text| {
            let bytes = decode_base64url(text).expect("canonical");
            json!({ "text": text, "bytes": bytes.len(), "hex": HEXLOWER.encode(&bytes) })
        })
        .collect();
    let rejected = [
        (
            low_bit_set(signature),
            64,
            "unused low bits of the last character are not zero",
        ),
        (
            low_bit_set(public_key),
            32,
            "unused low bits of the last character are not zero",
        ),
        (format!("{signature}=="), 64, "padding"),
        (format!("{public_key}="), 32, "padding"),
        (signature[..signature.len() - 1].to_owned(), 64, "truncated"),
        (format!("{signature}A"), 64, "one character too many"),
        (
            format!("+{}", &signature[1..]),
            64,
            "standard base64 alphabet",
        ),
        (format!("{} ", public_key), 32, "trailing space"),
    ];
    let rejected: Vec<Value> = rejected
        .iter()
        .map(|(text, bytes, reason)| {
            assert!(
                decode_base64url(text).is_none_or(|b| b.len() != *bytes),
                "{text} must be rejected ({reason})"
            );
            json!({ "text": text, "bytes": bytes, "reason": reason })
        })
        .collect();
    json!({ "accepted": accepted, "rejected": rejected })
}

/// A signed object as clients verify it: the canonical bytes, the id they
/// hash to and the message the signature (by the vector key) covers.
fn signed_vector<B: SignedBody>(object: &Signed<B>) -> Value {
    json!({
        "prefix": B::Kind::PREFIX,
        "signed_utf8": text(&object.canonical_bytes()),
        "message_hex": HEXLOWER.encode(&Signed::<B>::signing_message(&object.body)),
        "id": object.id().to_string(),
    })
}

#[test]
fn vectors_file_is_current() {
    let generated = serde_json::to_string_pretty(&build()).unwrap() + "\n";
    if std::env::var("AVER_REGEN_VECTORS").as_deref() == Ok("1") {
        std::fs::write(VECTORS_PATH, &generated).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(VECTORS_PATH).unwrap_or_default();
    assert!(
        committed == generated,
        "{VECTORS_PATH} is stale; regenerate with AVER_REGEN_VECTORS=1 cargo test -p aver-core --test vectors"
    );
}

#[test]
fn vectors_verify_independently_of_the_generator() {
    let vectors = build();
    let pk_bytes: [u8; 32] = HEXLOWER
        .decode(
            vectors["key"]["public_key_hex"]
                .as_str()
                .unwrap()
                .as_bytes(),
        )
        .unwrap()
        .try_into()
        .unwrap();
    let pk = VerifyingKey::from_bytes(&pk_bytes).unwrap();

    let signed = vectors["object_signature"]["signed_utf8"].as_str().unwrap();
    let transition = Transition::from_canonical(signed.as_bytes()).unwrap();
    assert_eq!(transition.verify(&pk), Ok(()));
    assert_eq!(
        transition.id().to_string(),
        vectors["object_signature"]["id"].as_str().unwrap()
    );

    for object in vectors["signed_objects"].as_array().unwrap() {
        let signed: Value = serde_json::from_str(object["signed_utf8"].as_str().unwrap()).unwrap();
        let sig: [u8; 64] = data_encoding::BASE64URL_NOPAD
            .decode(signed["signature"]["sig"].as_str().unwrap().as_bytes())
            .unwrap()
            .try_into()
            .unwrap();
        let message = HEXLOWER
            .decode(object["message_hex"].as_str().unwrap().as_bytes())
            .unwrap();
        pk.verify_strict(&message, &ed25519_dalek::Signature::from_bytes(&sig))
            .unwrap();
    }
}

#[test]
fn every_rust_decoder_refuses_non_canonical_base64url() {
    let vectors = build();
    for case in vectors["base64url"]["accepted"].as_array().unwrap() {
        let text = case["text"].as_str().unwrap();
        let bytes = decode_base64url(text).unwrap();
        assert_eq!(HEXLOWER.encode(&bytes), case["hex"].as_str().unwrap());
    }
    let signed = vectors["object_signature"]["signed_utf8"].as_str().unwrap();
    let canonical_sig = vectors["object_signature"]["signature_base64url"]
        .as_str()
        .unwrap();
    for case in vectors["base64url"]["rejected"].as_array().unwrap() {
        let text = case["text"].as_str().unwrap();
        let bytes = case["bytes"].as_u64().unwrap() as usize;
        assert!(
            decode_base64url(text).is_none_or(|b| b.len() != bytes),
            "{text}"
        );
        if bytes == 64 {
            assert!(signature_bytes(text).is_err(), "{text}");
            let tampered = signed.replace(canonical_sig, text);
            assert!(
                Transition::from_canonical(tampered.as_bytes()).is_err(),
                "a transition signed {text:?} must not parse"
            );
        }
    }
}

fn signature_bytes(text: &str) -> Result<aver_core::sig::SignatureBytes, SignatureError> {
    aver_core::sig::SignatureBytes::from_base64url(text)
}
